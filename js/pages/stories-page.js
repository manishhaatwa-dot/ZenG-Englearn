// =========================================================
// PUBLIC RENDER FUNCTION
// =========================================================

function renderStoriesPage(
  container,
  options = {}
) {

  if (!container) {
    return;
  }


  ensureStoriesStyles();


  renderStoriesList(
    container
  );

}


